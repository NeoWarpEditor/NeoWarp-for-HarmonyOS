#!/usr/bin/env node
/**
 * HAP 归档构建 + 结构校验
 *
 * 用法：
 *   node scripts/build_hap.mjs            # 构建
 *   node scripts/build_hap.mjs --verify   # 只校验现有 .hap
 *
 * 重要（诚实边界）：
 *   当前沙箱没有 HarmonyOS SDK / hvigor / 签名工具，无法把 ArkTS 编译为
 *   ets/modules.abc，也无法生成合法 resources.index 与应用签名。
 *   因此本脚本产出的是【开发态归档】：结构、配置、全部离线资源、源码齐备，
 *   并在 BUILD_INFO.json 中显式标注缺失项。绝不伪造 .abc 二进制。
 *   在 DevEco Studio 打开本工程执行 Build Hap(s) + 签名，即产出可安装 HAP。
 */

import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {execFileSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const PROJECT = path.resolve(__dirname, '..');
const ENTRY_MAIN = path.join(PROJECT, 'entry/src/main');
const RES = path.join(ENTRY_MAIN, 'resources');
const RAWF = path.join(RES, 'rawfile');
const DIST = path.join(PROJECT, 'dist');
// 早期开发态归档工具：输出独立文件名，避免覆盖 hvigor 真实编译 + 签名的交付产物。
const HAP = path.join(DIST, 'NeoWarp-2.3.0-devarchive.hap');
const VERIFY_ONLY = process.argv.includes('--verify');

function sha256 (file) {
  return crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');
}

function walk (dir, out = []) {
  if (!fs.existsSync(dir)) return out;
  for (const e of fs.readdirSync(dir, {withFileTypes: true})) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, out);
    else out.push(p);
  }
  return out;
}

/** 仅处理独占行的 // 注释（本工程 json5 配置均如此），避免误伤字符串内的 // */
function stripJson5Comments (text) {
  return text.split('\n').filter(line => !line.trim().startsWith('//')).join('\n');
}

function copyInto (from, to) {
  if (!fs.existsSync(from)) return 0;
  let n = 0;
  for (const file of walk(from)) {
    const rel = path.relative(from, file);
    const dst = path.join(to, rel);
    fs.mkdirSync(path.dirname(dst), {recursive: true});
    fs.copyFileSync(file, dst);
    n++;
  }
  return n;
}

function build () {
  fs.mkdirSync(DIST, {recursive: true});
  const tmp = fs.mkdtempSync('/tmp/neowarp-hap-');

  // 1) module.json（由 module.json5 转换；资源引用保留 $string 形式，编译时由 hvigor 解析）
  const moduleJson5 = fs.readFileSync(path.join(ENTRY_MAIN, 'module.json5'), 'utf-8');
  const moduleJson = JSON.parse(stripJson5Comments(moduleJson5));
  fs.writeFileSync(path.join(tmp, 'module.json'), JSON.stringify(moduleJson, null, 2), 'utf-8');

  // 2) pack.info
  const packInfo = {
    summary: {
      app: {
        bundleName: 'org.neowarp.harmony',
        vendor: 'NeoWarp',
        version: {name: '2.3.0', code: 2030000},
        minAPIVersion: 26,
        targetAPIVersion: 26
      },
      modules: [{
        name: 'entry',
        type: 'entry',
        mainAbility: 'EntryAbility',
        deviceTypes: moduleJson.module.deviceTypes,
        deliveryWithInstall: true,
        installationFree: false
      }]
    },
    packages: [{
      name: 'entry',
      moduleType: 'entry',
      deviceTypes: moduleJson.module.deviceTypes,
      deliveryWithInstall: true
    }]
  };
  fs.writeFileSync(path.join(tmp, 'pack.info'), JSON.stringify(packInfo, null, 2), 'utf-8');

  // 3) 资源（限定词目录 + rawfile 离线站点）
  const resCount = copyInto(RES, path.join(tmp, 'resources'));

  // 4) ArkTS 源码（便于审计；不是 modules.abc）
  const etsCount = copyInto(path.join(ENTRY_MAIN, 'ets'), path.join(tmp, 'ets/source'));

  // 5) 资源索引清单（JSON 描述，非编译产物 resources.index）
  const rawFiles = walk(RAWF).map(f => ({
    path: 'resources/rawfile/' + path.relative(RAWF, f).split(path.sep).join('/'),
    size: fs.statSync(f).size,
    sha256: sha256(f)
  }));
  fs.writeFileSync(path.join(tmp, 'resources.index.json'), JSON.stringify({
    note: 'Descriptive index, NOT the compiled resources.index binary.',
    fileCount: rawFiles.length,
    files: rawFiles
  }, null, 2), 'utf-8');

  // 6) 离线保证与构建边界说明
  const offlineManifest = path.join(RAWF, 'neowarp/offline-manifest.json');
  const offline = fs.existsSync(offlineManifest) ? JSON.parse(fs.readFileSync(offlineManifest, 'utf-8')) : null;
  const perms = (moduleJson.module.requestPermissions || []).map(p => p.name);
  const buildInfo = {
    product: 'NeoWarp HarmonyOS 7 (API 26)',
    version: '2.3.0',
    bundleName: 'org.neowarp.harmony',
    generatedAt: new Date().toISOString(),
    generatedBy: 'scripts/build_hap.mjs (dev archive)',
    archiveState: 'DEVELOPMENT_ARCHIVE',
    signed: false,
    installable: false,
    missingFromThisArchive: [
      'ets/modules.abc (requires ArkTS compilation by hvigor / DevEco Studio)',
      'resources.index (binary, generated by hvigor)',
      'signature (requires Huawei developer certificate + profile)'
    ],
    offlineGuarantees: {
      declaresInternetPermission: perms.includes('ohos.permission.INTERNET'),
      requestPermissions: perms,
      cspConnectSrc: 'self',
      externalFetchBlockedInHarmonyBridge: true,
      rawfileSiteBundled: true
    },
    offlineSite: offline ? {
      mode: offline.mode,
      fileCount: offline.fileCount,
      totalMB: offline.totalMB
    } : null,
    sourceFiles: {
      arkts: etsCount,
      resources: resCount
    },
    nextSteps: [
      'Open /workspace/NeoWarpHarmony in DevEco Studio with HarmonyOS SDK API 26',
      'ohpm install',
      'hvigorw assembleHap --mode module -p product=default -p buildMode=release',
      'Configure signing config, then hdc install the signed .hap'
    ]
  };
  fs.writeFileSync(path.join(tmp, 'BUILD_INFO.json'), JSON.stringify(buildInfo, null, 2), 'utf-8');

  // 7) 打 ZIP（HAP 本质是 zip 归档）
  if (fs.existsSync(HAP)) fs.rmSync(HAP);
  execFileSync('zip', ['-r', '-q', '-X', '-9', HAP, '.'], {cwd: tmp, stdio: 'pipe'});

  const size = fs.statSync(HAP).size;
  console.log('[hap] 产物: ' + HAP);
  console.log('[hap] 体积: ' + (size / 1024 / 1024).toFixed(2) + ' MB');
  console.log('[hap] ArkTS 源文件: ' + etsCount + ' · 资源文件: ' + resCount);
  console.log('[hap] 状态: 开发态归档（未编译 .abc / 未签名）');
  return tmp;
}

function verify () {
  if (!fs.existsSync(HAP)) {
    console.error('[verify] 找不到 ' + HAP);
    process.exit(1);
  }
  const report = {file: HAP, checkedAt: new Date().toISOString(), checks: []};
  const add = (name, ok, detail) => {
    report.checks.push({name, ok, detail});
    console.log((ok ? '  ✓ ' : '  ✗ ') + name + (detail ? ' — ' + detail : ''));
  };

  // zip 完整性
  let zipOk = true;
  let zipDetail = '';
  try {
    const out = execFileSync('unzip', ['-t', HAP], {stdio: ['ignore', 'pipe', 'pipe'], maxBuffer: 32 * 1024 * 1024}).toString();
    // 以退出码为准：unzip -t 检出错误时返回非零。不扫描输出文本，
    // 避免资源文件名里恰好含 bad/failed 等词造成误判。
    zipOk = true;
    zipDetail = out.trim().split('\n').slice(-1)[0];
  } catch (e) { zipOk = false; zipDetail = String(e.message || e); }
  add('ZIP 归档完整性 (unzip -t)', zipOk, zipDetail);

  const tmp = fs.mkdtempSync('/tmp/neowarp-verify-');
  execFileSync('unzip', ['-q', '-o', HAP, '-d', tmp], {stdio: 'pipe'});

  // 必需条目
  const required = ['module.json', 'pack.info', 'BUILD_INFO.json', 'resources.index.json'];
  for (const f of required) add('必需条目 ' + f, fs.existsSync(path.join(tmp, f)));

  // module.json 解析 + 零 INTERNET 权限
  let moduleJson = null;
  try {
    moduleJson = JSON.parse(fs.readFileSync(path.join(tmp, 'module.json'), 'utf-8'));
    add('module.json 可解析', true, 'abilities=' + moduleJson.module.abilities.length);
  } catch (e) { add('module.json 可解析', false, String(e.message || e)); }
  if (moduleJson) {
    const perms = (moduleJson.module.requestPermissions || []).map(p => p.name);
    add('零 INTERNET 权限（离线硬保证）', !perms.includes('ohos.permission.INTERNET'), perms.join(', ') || '无');
    add('deviceTypes 覆盖 PC/平板/折叠', ['phone', 'tablet', '2in1'].every(d => moduleJson.module.deviceTypes.includes(d)),
      moduleJson.module.deviceTypes.join(', '));
    add('文件关联 skills', moduleJson.module.abilities[0].skills.length >= 2,
      moduleJson.module.abilities[0].skills.length + ' 组');
  }

  // rawfile 资源校验和
  const manifestPath = path.join(tmp, 'resources/rawfile/neowarp/asset-manifest.json');
  if (fs.existsSync(manifestPath)) {
    const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf-8'));
    let bad = 0;
    for (const [rel, expected] of Object.entries(manifest.files)) {
      const f = path.join(tmp, 'resources/rawfile/neowarp', rel);
      if (!fs.existsSync(f) || sha256(f) !== expected) bad++;
    }
    add('rawfile 资源校验和', bad === 0,
      Object.keys(manifest.files).length + ' 个文件，损坏/缺失 ' + bad);
    add('离线站点已内置', Object.keys(manifest.files).length > 20,
      Object.keys(manifest.files).length + ' 个资源');
  } else {
    add('asset-manifest.json 存在', false);
  }

  // ArkTS 源码
  const etsFiles = walk(path.join(tmp, 'ets/source')).filter(f => f.endsWith('.ets'));
  add('ArkTS 源码齐备', etsFiles.length >= 10, etsFiles.length + ' 个 .ets');

  // 桥接层注入
  const bridge = path.join(tmp, 'resources/rawfile/neowarp/assets/harmony-bridge.js');
  add('harmony-bridge.js 内置', fs.existsSync(bridge));

  const size = fs.statSync(HAP).size;
  report.sizeBytes = size;
  report.sizeMB = Math.round(size / 1024 / 1024 * 100) / 100;
  report.passed = report.checks.filter(c => c.ok).length;
  report.total = report.checks.length;
  report.allPassed = report.passed === report.total;
  fs.writeFileSync(path.join(DIST, 'verify-report.json'), JSON.stringify(report, null, 2), 'utf-8');
  console.log('\n[verify] ' + report.passed + '/' + report.total + ' 项通过 → dist/verify-report.json');
  if (!report.allPassed) process.exitCode = 1;
}

if (!VERIFY_ONLY) build();
verify();
